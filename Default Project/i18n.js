/* ---------- Language state ---------- */
const LANG_STORAGE = "bf_lang";
let currentLang = "en";

function t(key) {
  const lang = I18N[currentLang] || I18N.en;
  const val = lang[key];
  return val !== undefined ? val : I18N.en[key] !== undefined ? I18N.en[key] : key;
}

function L(value) {
  if (value && typeof value === "object") {
    return value[currentLang] !== undefined ? value[currentLang] : value.en;
  }
  return value;
}

function interpolate(template, vars) {
  return template.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
}

function applyStaticLang() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
}

function setLang(lang) {
  currentLang = lang;
  try {
    localStorage.setItem(LANG_STORAGE, lang);
  } catch (e) {}
  applyStaticLang();
  const btn = document.getElementById("langBtn");
  if (btn) btn.textContent = currentLang === "en" ? "EN" : "SW";
  if (typeof applyDynamicLang === "function") applyDynamicLang();
}

function loadLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE);
    if (saved === "sw" || saved === "en") currentLang = saved;
  } catch (e) {}
}
